"""
Probe loader for GARAK probes adapted for PyRIT.

This module provides the ProbeLoader class that bridges GARAK-style probes
with PyRIT's seed dataset system. It converts prompts generated by GARAK
probes into PyRIT's SeedDataset/SeedPrompt format.

The loader follows the SeedDatasetProvider pattern used throughout PyRIT,
enabling GARAK probes to be used seamlessly with PyRIT's attack and
orchestration systems.

Example usage:
    >>> from pyrit.datasets.seed_datasets.garak.probe_loader import GarakProbeLoader
    >>> from pyrit.datasets.seed_datasets.garak.probes.apikey import GetKey
    >>>
    >>> # Create a loader for the GetKey probe
    >>> loader = GarakProbeLoader(probe_class=GetKey)
    >>>
    >>> # Fetch as a SeedDataset
    >>> dataset = await loader.fetch_dataset()
    >>>
    >>> # Get prompts
    >>> prompts = dataset.get_values()
"""

import importlib
import logging
import pkgutil
from pathlib import Path
from typing import Any, Dict, List, Optional, Type

from pyrit.datasets.seed_datasets.garak.probes.base import Probe
from pyrit.datasets.seed_datasets.seed_dataset_provider import SeedDatasetProvider
from pyrit.models import SeedDataset, SeedPrompt

logger = logging.getLogger(__name__)


class GarakProbeLoader(SeedDatasetProvider):
    """
    Loader that converts GARAK probes to PyRIT SeedDatasets.

    This class wraps a GARAK Probe instance and provides it through
    PyRIT's SeedDatasetProvider interface, enabling seamless integration
    with PyRIT's attack and orchestration systems.

    The flow is:
    1. ProbeLoader receives a Probe class or instance
    2. Probe generates prompts via _generate_prompts()
    3. ProbeLoader converts prompts to SeedPrompt objects
    4. Returns a SeedDataset containing all prompts

    Attributes:
        _probe_class: The Probe class to instantiate.
        _probe_config: Optional configuration for the probe.
        _probe_instance: The instantiated probe (created lazily).
    """

    # Don't auto-register the base class
    should_register = False

    def __init__(
        self,
        *,
        probe_class: Type[Probe],
        probe_config: Optional[Dict[str, Any]] = None,
    ) -> None:
        """
        Initialize the GarakProbeLoader.

        Args:
            probe_class: The GARAK Probe class to load.
            probe_config: Optional configuration dictionary for the probe.
        """
        self._probe_class = probe_class
        self._probe_config = probe_config or {}
        self._probe_instance: Optional[Probe] = None

    @property
    def dataset_name(self) -> str:
        """Return the dataset name based on the probe class."""
        return f"garak_{self._probe_class.__name__.lower()}"

    def _get_probe(self) -> Probe:
        """
        Get or create the probe instance.

        Returns:
            The Probe instance.
        """
        if self._probe_instance is None:
            self._probe_instance = self._probe_class(config=self._probe_config)
        return self._probe_instance

    async def fetch_dataset(self, *, cache: bool = True) -> SeedDataset:
        """
        Fetch the probe's prompts as a SeedDataset.

        Args:
            cache: Whether to cache the dataset. Currently not implemented
                   for GARAK probes as they are generated in-memory.

        Returns:
            SeedDataset containing the probe's prompts as SeedPrompt objects.
        """
        probe = self._get_probe()
        prompts = probe.get_prompts()
        attempts = probe.get_attempts()

        seeds: List[SeedPrompt] = []
        for i, prompt in enumerate(prompts):
            # Get corresponding attempt for metadata
            attempt = attempts[i] if i < len(attempts) else None

            seed = SeedPrompt(
                value=prompt,
                name=f"{probe.probename} prompt {i + 1}",
                dataset_name=self.dataset_name,
                data_type="text",
                harm_categories=probe.harm_categories,
                description=probe.description,
                source=f"GARAK probe: {probe.__class__.__module__}.{probe.__class__.__name__}",
                metadata={
                    "probe_class": probe.probename,
                    "goal": probe.goal,
                    "primary_detector": probe.primary_detector,
                    "tags": probe.tags,
                    **(attempt.notes if attempt else {}),
                },
            )
            seeds.append(seed)

        return SeedDataset(
            seeds=seeds,
            dataset_name=self.dataset_name,
            name=f"GARAK {probe.probename}",
            description=probe.description,
            harm_categories=probe.harm_categories,
            source=f"GARAK probe: {probe.__class__.__module__}",
        )


def discover_probe_classes(probes_path: Optional[Path] = None) -> Dict[str, Type[Probe]]:
    """
    Discover all Probe classes in the probes directory.

    This function scans the probes directory for Python modules containing
    Probe subclasses and returns them as a dictionary.

    Args:
        probes_path: Optional path to the probes directory. If None, uses
                     the default garak/probes directory.

    Returns:
        Dictionary mapping probe class names to Probe classes.
    """
    if probes_path is None:
        probes_path = Path(__file__).parent / "probes"

    discovered_probes: Dict[str, Type[Probe]] = {}

    # Get the package name for importing
    package_name = "pyrit.datasets.seed_datasets.garak.probes"

    for module_info in pkgutil.iter_modules([str(probes_path)]):
        if module_info.name.startswith("_") or module_info.name == "base":
            continue

        try:
            module = importlib.import_module(f"{package_name}.{module_info.name}")

            # Find all Probe subclasses in the module
            for name in dir(module):
                obj = getattr(module, name)
                if (
                    isinstance(obj, type)
                    and issubclass(obj, Probe)
                    and obj is not Probe
                    and getattr(obj, "active", True)
                ):
                    discovered_probes[name] = obj
                    logger.debug(f"Discovered probe: {name}")

        except Exception as e:
            logger.warning(f"Failed to import probe module {module_info.name}: {e}")

    return discovered_probes


def create_probe_dataset_loaders() -> Dict[str, GarakProbeLoader]:
    """
    Create GarakProbeLoader instances for all discovered probes.

    Returns:
        Dictionary mapping dataset names to GarakProbeLoader instances.
    """
    probe_classes = discover_probe_classes()
    loaders: Dict[str, GarakProbeLoader] = {}

    for probe_name, probe_class in probe_classes.items():
        loader = GarakProbeLoader(probe_class=probe_class)
        loaders[loader.dataset_name] = loader
        logger.debug(f"Created loader for probe: {probe_name} -> {loader.dataset_name}")

    return loaders


